"""Build English and Ukrainian docs into one Pages artifact."""

import argparse
import shutil
import subprocess
import sys
from urllib.parse import urlsplit

from check_site import check_site
from project import ROOT, SITE_URL, dump_yaml, load_yaml


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--site-url", default=SITE_URL)
    args = parser.parse_args()
    site_url = args.site_url.rstrip("/") + "/"
    url = urlsplit(site_url)
    if url.scheme not in ("http", "https") or not url.netloc or url.query or url.fragment:
        parser.error("--site-url must be an absolute HTTP(S) base URL")
    site = ROOT / "site"
    marker = site / ".worktree-kit-docs-generated"
    if site.is_symlink() or (site.exists() and not marker.is_file()):
        parser.error("Refusing to replace an unowned site/ directory")
    if site.exists():
        shutil.rmtree(site)
    site.mkdir()
    marker.write_text("Generated by DDEV Worktree Kit docs build\n")
    for language, filename in (("en", "mkdocs.yml"), ("uk", "mkdocs.uk.yml")):
        config = load_yaml((ROOT / filename).read_text())
        config["docs_dir"] = "docs/" + language
        config["site_dir"] = "site" if language == "en" else "site/uk"
        config["site_url"] = site_url + ("uk/" if language == "uk" else "")
        config["extra"]["alternate"] = [
            {"name": "English", "link": site_url, "lang": "en"},
            {"name": "Українська", "link": site_url + "uk/", "lang": "uk"},
        ]
        # Zensical treats the config directory as its project root. Keep the
        # temporary config here so both docs/ and site/ stay within that root.
        generated = ROOT / (".mkdocs-build-" + language + ".yml")
        if generated.is_symlink():
            parser.error("Refusing a symlink generated docs config")
        generated.write_text("# Generated by Worktree Kit docs build\n" + dump_yaml(config))
        subprocess.run(
            [
                sys.executable,
                "-m",
                "zensical",
                "build",
                "--clean",
                "--strict",
                "-f",
                str(generated),
            ],
            cwd=ROOT,
            check=True,
        )
        # Retain an ownership marker even if a later language build fails.
        marker.write_text("Generated by DDEV Worktree Kit docs build\n")
    (site / ".nojekyll").touch()
    pages, links = check_site(site, site_url)
    print(f"Bilingual docs: PASS ({pages} HTML pages, {links} local links/assets)")


if __name__ == "__main__":
    main()
